"""Two-tone komainu. '#' = full tone, 'm' = shadow tone (mane/tail), '.' = empty. Facing right."""

A = """
....m.m.m.m.........
...mmmmmmmmmm.......
..mmmm######m.......
..mmm#########......
.mmmm###.######.....
.mmmm###########....
.mmmm####.....#.....
.mmmm###########....
..mmmm#mmmm.........
..mmmmmmmmm.........
m..mmm##########....
mm.#############....
.mm#############....
.mm####.####.##.....
..m####.####.##.....
...####.####.###....
####################
####################
"""

# "un": mouth closed — fill the gap row
UN_FILL = [(6, x) for x in range(9, 16)]

def grid(art):
    return [list(r) for r in art.strip("\n").split("\n")]

def lion(open_mouth=True):
    g = grid(A)
    if not open_mouth:
        for y, x in UN_FILL: g[y][x] = "#"
    return g

def mirror(g):
    return [r[::-1] for r in g]

TONE = {".": 0, "m": 1, "#": 2, "o": 0}
# (top, bottom) tone pair -> logo character. ';' is a new marker: full-tone ▄ on a shadow background.
CELL = {(0, 0): " ", (2, 2): "█", (2, 0): "▀", (0, 2): "▄", (1, 1): "_", (1, 0): "~", (0, 1): ",", (2, 1): "^", (1, 2): ";"}

def to_cells(g):
    out = []
    for y in range(0, len(g), 2):
        top, bot = g[y], g[y + 1]
        out.append("".join(CELL[(TONE[t], TONE[b])] for t, b in zip(top, bot)))
    return out
